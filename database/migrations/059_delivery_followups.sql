CREATE TABLE IF NOT EXISTS delivery_followups (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    order_id BIGINT UNSIGNED NOT NULL,
    supplier_id BIGINT UNSIGNED NOT NULL,
    proposal_id BIGINT UNSIGNED NOT NULL,
    sent_by BIGINT UNSIGNED NOT NULL,
    sent_at DATETIME(3) NOT NULL,
    message TEXT NOT NULL,
    source_snapshot JSON NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'SENT',
    replied_by BIGINT UNSIGNED NULL,
    replied_at DATETIME(3) NULL,
    reply_message VARCHAR(1000) NULL,
    reply_expected_date DATE NULL,
    reply_request_key VARCHAR(100) NULL,
    reply_payload_hash CHAR(64) NULL,
    CONSTRAINT uq_delivery_followup_proposal UNIQUE (proposal_id),
    CONSTRAINT fk_delivery_followup_order FOREIGN KEY (order_id) REFERENCES purchase_orders(id),
    CONSTRAINT fk_delivery_followup_supplier FOREIGN KEY (supplier_id) REFERENCES suppliers(id),
    CONSTRAINT fk_delivery_followup_proposal FOREIGN KEY (proposal_id) REFERENCES ai_agent_action_proposals(id),
    CONSTRAINT fk_delivery_followup_sender FOREIGN KEY (sent_by) REFERENCES sys_users(id),
    CONSTRAINT fk_delivery_followup_replier FOREIGN KEY (replied_by) REFERENCES sys_users(id),
    CONSTRAINT ck_delivery_followup_status CHECK (status IN ('SENT','REPLIED')),
    INDEX ix_delivery_followup_order (order_id, sent_at),
    INDEX ix_delivery_followup_supplier (supplier_id, sent_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
