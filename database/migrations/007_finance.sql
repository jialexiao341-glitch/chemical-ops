-- ChemicalOps 财务对账、发票、付款和结算增量迁移。
-- 金额均保存为订单币种金额；服务层负责校验金额累计和状态流转。

CREATE TABLE IF NOT EXISTS finance_reconciliations (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT COMMENT '主键',
    reconciliation_no VARCHAR(32) NOT NULL COMMENT '对账单业务编号',
    po_id BIGINT UNSIGNED NOT NULL COMMENT '采购订单 ID，一张订单只允许一张对账单',
    supplier_id BIGINT UNSIGNED NOT NULL COMMENT '供应商 ID 快照关联',
    currency_code CHAR(3) NOT NULL DEFAULT 'CNY' COMMENT '结算币种',
    total_amount DECIMAL(18,6) NOT NULL COMMENT '对账应付总额',
    status VARCHAR(20) NOT NULL DEFAULT 'DRAFT' COMMENT 'DRAFT、CONFIRMED、DISPUTED、CLOSED、CANCELLED',
    created_by BIGINT UNSIGNED NOT NULL COMMENT '创建人用户 ID',
    confirmed_by BIGINT UNSIGNED NULL COMMENT '确认人用户 ID',
    confirmed_at DATETIME(3) NULL COMMENT '确认时间',
    closed_at DATETIME(3) NULL COMMENT '结算关闭时间',
    cancelled_at DATETIME(3) NULL COMMENT '取消时间',
    cancel_reason VARCHAR(1000) NULL COMMENT '取消原因',
    note VARCHAR(1000) NULL COMMENT '对账备注',
    created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) COMMENT '创建时间',
    updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3) COMMENT '更新时间',
    PRIMARY KEY (id),
    UNIQUE KEY uk_finance_reconciliation_no (reconciliation_no),
    UNIQUE KEY uk_finance_reconciliation_po (po_id),
    KEY idx_finance_reconciliation_supplier_status (supplier_id, status),
    KEY idx_finance_reconciliation_status_time (status, created_at),
    CONSTRAINT fk_finance_reconciliation_po FOREIGN KEY (po_id) REFERENCES purchase_orders (id),
    CONSTRAINT fk_finance_reconciliation_supplier FOREIGN KEY (supplier_id) REFERENCES suppliers (id),
    CONSTRAINT fk_finance_reconciliation_creator FOREIGN KEY (created_by) REFERENCES sys_users (id),
    CONSTRAINT fk_finance_reconciliation_confirmer FOREIGN KEY (confirmed_by) REFERENCES sys_users (id),
    CONSTRAINT chk_finance_reconciliation_amount CHECK (total_amount > 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='财务对账主单';

CREATE TABLE IF NOT EXISTS finance_invoices (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT COMMENT '主键',
    invoice_no VARCHAR(32) NOT NULL COMMENT '系统发票记录编号',
    reconciliation_id BIGINT UNSIGNED NOT NULL COMMENT '对账单 ID',
    po_id BIGINT UNSIGNED NOT NULL COMMENT '采购订单 ID',
    supplier_id BIGINT UNSIGNED NOT NULL COMMENT '供应商 ID',
    invoice_code VARCHAR(32) NULL COMMENT '发票代码，电子票可能为空',
    invoice_number VARCHAR(64) NOT NULL COMMENT '发票号码',
    invoice_date DATE NOT NULL COMMENT '开票日期',
    amount_excl_tax DECIMAL(18,6) NOT NULL COMMENT '不含税金额',
    tax_amount DECIMAL(18,6) NOT NULL DEFAULT 0 COMMENT '税额',
    amount_incl_tax DECIMAL(18,6) NOT NULL COMMENT '价税合计',
    currency_code CHAR(3) NOT NULL DEFAULT 'CNY' COMMENT '发票币种',
    status VARCHAR(20) NOT NULL DEFAULT 'DRAFT' COMMENT 'DRAFT、SUBMITTED、VERIFIED、REJECTED、VOIDED',
    source_file_id BIGINT UNSIGNED NULL COMMENT '发票附件文件 ID',
    submitted_by BIGINT UNSIGNED NOT NULL COMMENT '录入人用户 ID',
    verified_by BIGINT UNSIGNED NULL COMMENT '核验人用户 ID',
    verified_at DATETIME(3) NULL COMMENT '核验时间',
    reject_reason VARCHAR(1000) NULL COMMENT '驳回原因',
    note VARCHAR(1000) NULL COMMENT '发票备注',
    created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) COMMENT '创建时间',
    updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3) COMMENT '更新时间',
    PRIMARY KEY (id),
    UNIQUE KEY uk_finance_invoice_no (invoice_no),
    UNIQUE KEY uk_finance_invoice_supplier_number (supplier_id, invoice_number),
    KEY idx_finance_invoice_reconciliation_status (reconciliation_id, status),
    KEY idx_finance_invoice_supplier_date (supplier_id, invoice_date),
    CONSTRAINT fk_finance_invoice_reconciliation FOREIGN KEY (reconciliation_id) REFERENCES finance_reconciliations (id),
    CONSTRAINT fk_finance_invoice_po FOREIGN KEY (po_id) REFERENCES purchase_orders (id),
    CONSTRAINT fk_finance_invoice_supplier FOREIGN KEY (supplier_id) REFERENCES suppliers (id),
    CONSTRAINT fk_finance_invoice_file FOREIGN KEY (source_file_id) REFERENCES sys_files (id),
    CONSTRAINT fk_finance_invoice_submitter FOREIGN KEY (submitted_by) REFERENCES sys_users (id),
    CONSTRAINT fk_finance_invoice_verifier FOREIGN KEY (verified_by) REFERENCES sys_users (id),
    CONSTRAINT chk_finance_invoice_amounts CHECK (amount_excl_tax >= 0 AND tax_amount >= 0 AND amount_incl_tax >= 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='供应商发票记录';

CREATE TABLE IF NOT EXISTS finance_payments (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT COMMENT '主键',
    payment_no VARCHAR(32) NOT NULL COMMENT '付款单业务编号',
    reconciliation_id BIGINT UNSIGNED NOT NULL COMMENT '对账单 ID',
    po_id BIGINT UNSIGNED NOT NULL COMMENT '采购订单 ID',
    supplier_id BIGINT UNSIGNED NOT NULL COMMENT '供应商 ID',
    amount DECIMAL(18,6) NOT NULL COMMENT '本次付款金额',
    currency_code CHAR(3) NOT NULL DEFAULT 'CNY' COMMENT '付款币种',
    payment_method VARCHAR(32) NOT NULL COMMENT 'BANK_TRANSFER、CASH、OTHER',
    status VARCHAR(20) NOT NULL DEFAULT 'REQUESTED' COMMENT 'REQUESTED、APPROVED、PAID、REJECTED、CANCELLED',
    requested_by BIGINT UNSIGNED NOT NULL COMMENT '申请人用户 ID',
    approved_by BIGINT UNSIGNED NULL COMMENT '审批人用户 ID',
    paid_by BIGINT UNSIGNED NULL COMMENT '实际付款操作人用户 ID',
    approved_at DATETIME(3) NULL COMMENT '审批时间',
    paid_at DATETIME(3) NULL COMMENT '付款时间',
    transaction_ref VARCHAR(128) NULL COMMENT '银行流水号或外部支付流水号',
    reject_reason VARCHAR(1000) NULL COMMENT '驳回原因',
    note VARCHAR(1000) NULL COMMENT '付款备注',
    created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) COMMENT '创建时间',
    updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3) COMMENT '更新时间',
    PRIMARY KEY (id),
    UNIQUE KEY uk_finance_payment_no (payment_no),
    KEY idx_finance_payment_reconciliation_status (reconciliation_id, status),
    KEY idx_finance_payment_supplier_date (supplier_id, paid_at),
    CONSTRAINT fk_finance_payment_reconciliation FOREIGN KEY (reconciliation_id) REFERENCES finance_reconciliations (id),
    CONSTRAINT fk_finance_payment_po FOREIGN KEY (po_id) REFERENCES purchase_orders (id),
    CONSTRAINT fk_finance_payment_supplier FOREIGN KEY (supplier_id) REFERENCES suppliers (id),
    CONSTRAINT fk_finance_payment_requester FOREIGN KEY (requested_by) REFERENCES sys_users (id),
    CONSTRAINT fk_finance_payment_approver FOREIGN KEY (approved_by) REFERENCES sys_users (id),
    CONSTRAINT fk_finance_payment_payer FOREIGN KEY (paid_by) REFERENCES sys_users (id),
    CONSTRAINT chk_finance_payment_amount CHECK (amount > 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='付款申请和付款记录';

CREATE TABLE IF NOT EXISTS finance_settlements (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT COMMENT '主键',
    settlement_no VARCHAR(32) NOT NULL COMMENT '结算单业务编号',
    reconciliation_id BIGINT UNSIGNED NOT NULL COMMENT '对账单 ID，一张对账单只允许一张结算单',
    po_id BIGINT UNSIGNED NOT NULL COMMENT '采购订单 ID',
    supplier_id BIGINT UNSIGNED NOT NULL COMMENT '供应商 ID',
    settlement_amount DECIMAL(18,6) NOT NULL COMMENT '结算金额',
    currency_code CHAR(3) NOT NULL DEFAULT 'CNY' COMMENT '结算币种',
    status VARCHAR(20) NOT NULL DEFAULT 'DRAFT' COMMENT 'DRAFT、CONFIRMED、CANCELLED',
    created_by BIGINT UNSIGNED NOT NULL COMMENT '创建人用户 ID',
    confirmed_by BIGINT UNSIGNED NULL COMMENT '确认人用户 ID',
    confirmed_at DATETIME(3) NULL COMMENT '确认时间',
    cancelled_at DATETIME(3) NULL COMMENT '取消时间',
    cancel_reason VARCHAR(1000) NULL COMMENT '取消原因',
    note VARCHAR(1000) NULL COMMENT '结算备注',
    created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) COMMENT '创建时间',
    updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3) COMMENT '更新时间',
    PRIMARY KEY (id),
    UNIQUE KEY uk_finance_settlement_no (settlement_no),
    UNIQUE KEY uk_finance_settlement_reconciliation (reconciliation_id),
    KEY idx_finance_settlement_supplier_status (supplier_id, status),
    CONSTRAINT fk_finance_settlement_reconciliation FOREIGN KEY (reconciliation_id) REFERENCES finance_reconciliations (id),
    CONSTRAINT fk_finance_settlement_po FOREIGN KEY (po_id) REFERENCES purchase_orders (id),
    CONSTRAINT fk_finance_settlement_supplier FOREIGN KEY (supplier_id) REFERENCES suppliers (id),
    CONSTRAINT fk_finance_settlement_creator FOREIGN KEY (created_by) REFERENCES sys_users (id),
    CONSTRAINT fk_finance_settlement_confirmer FOREIGN KEY (confirmed_by) REFERENCES sys_users (id),
    CONSTRAINT chk_finance_settlement_amount CHECK (settlement_amount > 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='采购结算单';
