CREATE TABLE ai_agent_action_proposals (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    confirmation_id CHAR(32) NOT NULL,
    user_id BIGINT UNSIGNED NOT NULL,
    action_type VARCHAR(80) NOT NULL,
    resource_type VARCHAR(64) NULL,
    resource_id VARCHAR(64) NULL,
    preview_version INT UNSIGNED NOT NULL DEFAULT 1,
    payload JSON NOT NULL,
    payload_hash CHAR(64) NOT NULL,
    expected_resource_snapshot JSON NOT NULL,
    diff JSON NOT NULL,
    evidence JSON NOT NULL,
    warnings JSON NOT NULL,
    blockers JSON NOT NULL,
    permission_code VARCHAR(100) NOT NULL,
    risk_level VARCHAR(20) NOT NULL DEFAULT 'LOW',
    idempotency_key VARCHAR(100) NOT NULL,
    expires_at DATETIME(3) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    result JSON NULL,
    created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
    executed_at DATETIME(3) NULL,
    CONSTRAINT uq_ai_action_proposal_confirmation UNIQUE (confirmation_id),
    CONSTRAINT uq_ai_action_proposal_user_idempotency UNIQUE (user_id, idempotency_key),
    CONSTRAINT fk_ai_action_proposal_user FOREIGN KEY (user_id) REFERENCES sys_users(id),
    INDEX ix_ai_action_proposal_owner_status (user_id, status),
    INDEX ix_ai_action_proposal_expiry_status (status, expires_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
